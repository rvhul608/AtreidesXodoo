import { afterAll, beforeEach, describe, expect, it, vi } from 'vitest';
import request from 'supertest';
import { pool } from '../src/common/db.js';
import { app } from '../src/index.js';
import { deliverNextEmail, mailConfig } from '../src/modules/outbox/delivery.js';

const config = { apiKey: 'unit-test-key', from: 'Brightloop <billing@example.org>' };
async function enqueue(recipient = 'customer@example.org') {
  const result = await pool.query<{ id: string }>(`INSERT INTO outbox_emails (recipient, subject, body)
    VALUES ($1, 'Test message', 'A message') RETURNING id`, [recipient]);
  return result.rows[0].id;
}
async function row(id: string) { return (await pool.query('SELECT * FROM outbox_emails WHERE id=$1', [id])).rows[0]; }

beforeEach(async () => { await pool.query('TRUNCATE outbox_emails CASCADE'); });
afterAll(async () => { await pool.end(); });

describe('Resend transactional outbox', () => {
  it('requires both a key and a sender before enabling delivery', () => {
    expect(mailConfig({})).toBeNull();
    expect(mailConfig({ RESEND_API_KEY: 'key' })).toBeNull();
    expect(mailConfig({ RESEND_API_KEY: config.apiKey, MAIL_FROM: config.from })).toEqual(config);
  });

  it('claims concurrently without double sending, records provider acceptance, and sends a stable idempotency key', async () => {
    const id = await enqueue();
    const send = vi.fn<typeof fetch>(async (_url, init) => {
      expect(init?.headers).toMatchObject({ Authorization: 'Bearer unit-test-key', 'Idempotency-Key': expect.stringContaining('brightloop-outbox/') });
      expect(JSON.parse(String(init?.body))).toEqual({ from: config.from, to: ['customer@example.org'], subject: 'Test message', text: 'A message' });
      return Response.json({ id: 'resend-123' });
    });
    await Promise.all([deliverNextEmail(config, pool, send), deliverNextEmail(config, pool, send)]);
    expect(send).toHaveBeenCalledOnce();
    expect(await row(id)).toMatchObject({ delivery_status: 'sent', provider_id: 'resend-123', attempts: 1 });
    expect(await deliverNextEmail(config, pool, send)).toBe(false);
  });

  it('backs off on 429 and retries the same frozen payload even if the sender changes', async () => {
    const id = await enqueue();
    const send = vi.fn<typeof fetch>()
      .mockResolvedValueOnce(new Response('', { status: 429, headers: { 'retry-after': '60' } }))
      .mockResolvedValueOnce(Response.json({ id: 'retry-accepted' }));
    await deliverNextEmail(config, pool, send);
    const pending = await row(id);
    expect(pending.delivery_status).toBe('pending');
    expect(new Date(pending.next_attempt_at).getTime() - Date.now()).toBeGreaterThan(55000);
    expect(await deliverNextEmail(config, pool, send)).toBe(false);
    await pool.query('UPDATE outbox_emails SET next_attempt_at = NOW() WHERE id=$1', [id]);
    await deliverNextEmail({ ...config, from: 'Changed <changed@example.org>' }, pool, send);
    expect(send.mock.calls[0][1]?.body).toBe(send.mock.calls[1][1]?.body);
    expect(send.mock.calls[0][1]?.headers).toEqual(send.mock.calls[1][1]?.headers);
    expect((await row(id)).delivery_status).toBe('sent');
  });

  it('recovers a crashed lease, retries network failures, and stops on permanent rejection', async () => {
    const id = await enqueue();
    const send = vi.fn<typeof fetch>().mockRejectedValueOnce(new Error('timeout'))
      .mockResolvedValueOnce(new Response('', { status: 422 }));
    await deliverNextEmail(config, pool, send);
    expect((await row(id)).delivery_status).toBe('pending');
    await pool.query("UPDATE outbox_emails SET delivery_status='sending', locked_until=NOW() - INTERVAL '1 second' WHERE id=$1", [id]);
    await deliverNextEmail(config, pool, send);
    expect(await row(id)).toMatchObject({ delivery_status: 'failed', attempts: 2 });
  });

  it('skips demo recipients and expired reset links, and stops uncertain retries before the provider key expires', async () => {
    const demo = await enqueue('admin@brightloop.local');
    const expired = await enqueue();
    const uncertain = await enqueue();
    await pool.query("UPDATE outbox_emails SET expires_at=NOW() - INTERVAL '1 minute' WHERE id=$1", [expired]);
    await pool.query("UPDATE outbox_emails SET first_attempt_at=NOW() - INTERVAL '24 hours' WHERE id=$1", [uncertain]);
    const send = vi.fn<typeof fetch>();
    await deliverNextEmail(config, pool, send);
    expect((await row(demo)).delivery_status).toBe('skipped');
    expect((await row(expired)).delivery_status).toBe('skipped');
    expect((await row(uncertain)).delivery_status).toBe('failed');
    expect(send).not.toHaveBeenCalled();
  });

  it('delivers an actual reset email generated by the auth route and consumes its link once', async () => {
    const email = 'mail-reset@example.org';
    await request(app).post('/api/auth/signup').send({ email, password: 'OriginalPass1!' }).expect(201);
    await request(app).post('/api/auth/forgot-password').send({ email }).expect(200);
    let body = '';
    const send = vi.fn<typeof fetch>(async (_url, init) => {
      body = JSON.parse(String(init?.body)).text;
      return Response.json({ id: 'reset-sent' });
    });
    await deliverNextEmail(config, pool, send);
    const token = new URL(body.match(/https?:\/\/\S+/)![0]).searchParams.get('token');
    await request(app).post('/api/auth/reset-password').send({ token, password: 'NewPassword1!' }).expect(200);
    await request(app).post('/api/auth/reset-password').send({ token, password: 'NewPassword2!' }).expect(400);
    await request(app).post('/api/auth/login').send({ email, password: 'NewPassword1!' }).expect(200);
  });
});
